#pragma once

#include <cstddef>
#include <cstdint>

#include "rb/core/result.hpp"
#include "rb/core/span.hpp"

namespace rb::netsio {

// NetSIO message IDs (FEP-003, "NetSIO protocol" table; docs/fuentes.md).
namespace id {
constexpr uint8_t kDataByte = 0x01;
constexpr uint8_t kDataBlock = 0x02;
constexpr uint8_t kDataByteSync = 0x09;
constexpr uint8_t kCommandOff = 0x10;
constexpr uint8_t kCommandOn = 0x11;
constexpr uint8_t kCommandOffSync = 0x18;
constexpr uint8_t kMotorOff = 0x20;
constexpr uint8_t kMotorOn = 0x21;
constexpr uint8_t kProceedOff = 0x30;
constexpr uint8_t kProceedOn = 0x31;
constexpr uint8_t kInterruptOff = 0x40;
constexpr uint8_t kInterruptOn = 0x41;
constexpr uint8_t kSpeedChange = 0x80;
constexpr uint8_t kSyncResponse = 0x81;
constexpr uint8_t kDeviceDisconnected = 0xC0;
constexpr uint8_t kDeviceConnected = 0xC1;
constexpr uint8_t kPingRequest = 0xC2;
constexpr uint8_t kPingResponse = 0xC3;
constexpr uint8_t kAliveRequest = 0xC4;
constexpr uint8_t kAliveResponse = 0xC5;
constexpr uint8_t kCreditStatus = 0xC6;
constexpr uint8_t kCreditUpdate = 0xC7;
constexpr uint8_t kWarmReset = 0xFE;
constexpr uint8_t kColdReset = 0xFF;
}  // namespace id

// Sync response acknowledgment types (FEP-003).
namespace ack {
constexpr uint8_t kEmpty = 0;  // device not interested: ack_byte and write_size ignored
constexpr uint8_t kValid = 1;  // ack_byte is delivered to the Atari
}  // namespace ack

constexpr std::size_t kMaxDataBlock = 512;  // FEP-003: "up to 512"
// Largest datagram either side may send: ID + data block + one trailing byte.
constexpr std::size_t kMaxDatagram = 1 + kMaxDataBlock + 1;
constexpr std::size_t kSyncResponseSize = 6;

// How the peer frames the messages it forwards from the emulated Atari (ADR-016).
//   Fep003Strict:          exactly the parameter lengths of FEP-003.
//   NetsiohubTrailingByte: every message the hub forwards from the Atari (IDs
//     01, 02, 09, 10, 11, 18, 20, 21, 80, FE, FF) carries one extra trailing
//     byte, observed in Issue #32 E0 (498 datagrams, incrementing by one) and not
//     described by FEP-003. It is stripped and reported, never interpreted.
//     Messages generated by the hub itself (C3, C5, C7) have no trailing byte.
enum class PeerProfile : uint8_t {
    Fep003Strict,
    NetsiohubTrailingByte,
};

// A decoded datagram. `payload` points into the datagram passed to decode()
// and is valid only while that buffer is (ADR-011: no copy, no allocation).
struct Message {
    uint8_t id;
    rb::core::Span<const uint8_t> payload;
    bool hasTrailer;
    uint8_t trailer;
};

// InvalidArgument for an empty datagram, an unknown ID or a length that does not
// match the ID under `profile`. Pure function of its inputs.
rb::core::Result<Message> decode(rb::core::Span<const uint8_t> datagram, PeerProfile profile) noexcept;

// True for the IDs that travel from the Atari to the device (and thus carry the
// trailing byte under NetsiohubTrailingByte).
bool fromAtari(uint8_t messageId) noexcept;

// Encoders write into `out` and return the datagram length. Preconditions
// (asserted): `out` is large enough; a data block holds 1..kMaxDataBlock bytes.
std::size_t encodeSyncResponse(rb::core::Span<uint8_t> out, uint8_t syncNumber, uint8_t ackType, uint8_t ackByte,
                               uint16_t writeSize) noexcept;
std::size_t encodeDataBlock(rb::core::Span<uint8_t> out, rb::core::Span<const uint8_t> data) noexcept;
std::size_t encodeCreditStatus(rb::core::Span<uint8_t> out, uint8_t remainingCredit) noexcept;
std::size_t encodeSignal(rb::core::Span<uint8_t> out, uint8_t messageId) noexcept;  // ID with no parameters
// SPEED_CHANGE (80) with the rate as 4 bytes LE: the cassette's rate (cassette-cas C002).
std::size_t encodeSpeedChange(rb::core::Span<uint8_t> out, uint32_t baud) noexcept;

}  // namespace rb::netsio
